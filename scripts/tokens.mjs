// Generates src/tokens.css from design/tokens.json. Run: node scripts/tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const t = JSON.parse(readFileSync(new URL("../design/tokens.json", import.meta.url), "utf8"));
const px = (v) => (typeof v === "number" ? `${v}px` : v);
const lines = [];
for (const [k, v] of Object.entries(t.color)) lines.push(`--c-${k}: ${v};`);
for (const [k, v] of Object.entries(t.font)) lines.push(`--font-${k}: ${v};`);
for (const [k, v] of Object.entries(t.type))
  lines.push(`--fs-${k}: ${v.size}px;`, `--lh-${k}: ${v.line}px;`, `--fw-${k}: ${v.weight};`);
t.space.forEach((v, i) => lines.push(`--sp-${i}: ${v}px;`));
for (const [k, v] of Object.entries(t.radius)) lines.push(`--r-${k}: ${px(v)};`);
for (const [k, v] of Object.entries(t.shadow)) lines.push(`--shadow-${k}: ${v};`);
for (const [k, v] of Object.entries(t.motion)) lines.push(`--m-${k}: ${v};`);
for (const [k, v] of Object.entries(t.layout)) lines.push(`--l-${k}: ${px(v)};`);

writeFileSync(
  new URL("../src/tokens.css", import.meta.url),
  `/* generated by scripts/tokens.mjs from design/tokens.json; do not edit */\n:root {\n  ${lines.join("\n  ")}\n}\n`,
);
console.log(`tokens.css: ${lines.length} properties`);
